"""Generating candidates through the provider  (FR-002.10, FR-002.11, FR-002.16).

**F2 implements no generation path and names no sibling.** Generation goes through
:mod:`providers.base` (ADR-009): miLLM is one row beside vLLM, Ollama and the OpenAI API,
and the default is in-process, which needs nothing. R-02.49 exists because *"a test path
wired to one sibling by name is what made the whole document depend on it"* - so the one
call here is to an interface, and the implementations are F3's (HTTP) and F4's
(in-process). **If the in-process implementation has not landed, that is foundation work -
a second one written here would be two answers to "which model answered."**

## The identity is captured from the reply, not assumed from the configuration

R-02.8 requires the resolved model name on every self-generation batch, and PPRD §7 says
why: *"tell the operator which model answered ... so no result is ever attributed to the
wrong version."* A configured model name is what was asked for; the reply says what
answered, and on the in-process path the **step** is part of the answer - the parameters
move every step, so candidates generated at step 40 are not candidates generated at step
41. An identity that cannot be resolved **refuses the batch** rather than being guessed.

## Where this runs

In the ``train`` worker, synchronously, inside the loop (F6's AMB-1). ADR-009's default
provider generates from the parameters miForge holds, which live only there - a ``generate``
worker would need a **second copy of the parameter set on the leased card**, against
ADR-008's one-run-per-card lease and BRD §6's budget. This module therefore declares no
Celery task and takes no second GPU lease; it adds no ``nvidia-smi`` call, no index and no
bus address (ADR-008).

Generation is bounded by configuration and **serialises against the step**: GPU sharing on
this node is time-slicing with no CUDA MPS, so a throughput figure taken on an idle card is
not the figure a shared card gives (ADR-024, BRD §9).
"""

from __future__ import annotations

import time
from collections.abc import Sequence
from typing import Any

from core.errors import Refusal, refuse
from providers.base import Completion, GenerationParams, ProviderIdentity
from training.signals.settings import SignalSettings


class GenerationCancelled(Refusal):
    """A cooperative cancellation between completions, as a **named** refusal.

    A refusal rather than a bare exception because the caller must tell "the run was
    cancelled" from "the provider is down": both stop the batch, and only one is a problem.
    """

    def __init__(self, completed: int, total: int) -> None:
        super().__init__(
            "generation_cancelled",
            f"Generation was cancelled after {completed} of {total} prompts. The partial "
            f"batch is discarded and no step starts: a batch is assembled and recorded, or "
            f"it is not handed to a step.",
            {"completed": completed, "total": total},
        )


def resolved_model(identity: ProviderIdentity, *, step: int | None) -> str:
    """The string ``batch-record-v1.json``'s ``resolved_model`` carries.

    ``provider:model`` for an endpoint, which already names its ``base_url``; for the
    in-process provider the **step is appended**, because the parameters it generated from
    are this run's and they move every step. *Candidates generated by two different models
    are not interchangeable* - the schema's own words - and two steps of one run are two
    different models for this purpose.
    """
    base = identity.record()
    if identity.base_url is None and step is not None:
        return f"{base}@{step}"
    return base


def generate(
    prompts: Sequence[str],
    provider: Any,
    params: GenerationParams,
    *,
    settings: SignalSettings,
    is_cancelled: Any | None = None,
    current_step: Any | None = None,
) -> tuple[tuple[Completion, ...], ProviderIdentity, str]:
    """Generate one completion per prompt, in order, bounded and cancellable.

    Args:
        prompts: The prompts to answer, positionally. **Order is part of the contract**:
            callers join completions to prompts by position, so a reordered or short reply
            would misattribute every candidate after the gap.
        provider: Anything satisfying :class:`providers.base.InferenceProvider`.
        params: Decode parameters. Part of what the batch *is*, not an incidental argument.
        settings: Supplies the concurrency bound, the explicit timeout and the length caps.
        is_cancelled: Checked **between** chunks, never inside one completion.
        current_step: Returns the run's current step, for the in-process identity.

    Returns:
        ``(completions, identity, resolved_model)``.

    Raises:
        Refusal: ``prompt_too_long`` (bounded **before** the call, never truncated);
            ``generation_failed`` for any provider error, which **refuses the whole batch**
            and substitutes no completion (E-6); ``generation_short_reply`` when the
            provider returns a different number of completions than prompts;
            ``generating_identity_unresolved`` when the reply names no model (FR-002.11);
            ``generation_cancelled``.
    """
    if provider is None:
        raise refuse(
            "generation_provider_not_configured",
            "This source generates its own candidates and no inference provider is bound. "
            "The default is in-process and needs no sibling; configure one, or use the "
            "corpus source, which reads material rather than generating it.",
            capabilities_unavailable=["self-generation", "reward"],
        )

    for index, prompt in enumerate(prompts):
        if len(prompt) > settings.max_prompt_chars:
            # Bounded BEFORE the call, and refused rather than truncated: truncation
            # changes the training example and the verdict without changing any hash, so
            # the record would describe a batch that was never generated.
            raise refuse(
                "prompt_too_long",
                f"Prompt {index} is {len(prompt)} characters, over the configured "
                f"{settings.max_prompt_chars}. Refusing rather than truncating: a truncated "
                f"prompt changes what was generated and what was judged, and no hash in the "
                f"record would differ.",
                index=index,
                length=len(prompt),
                limit=settings.max_prompt_chars,
            )

    completions: list[Completion] = []
    chunk = max(1, settings.generation_concurrency)
    total = len(prompts)
    started = time.monotonic()
    for start in range(0, total, chunk):
        if is_cancelled is not None and is_cancelled():
            raise GenerationCancelled(completed=len(completions), total=total)
        elapsed = time.monotonic() - started
        if elapsed > settings.generation_timeout_s:
            # THE BATCH's budget, not a request's. A provider owns its own connect and read
            # timeouts - F3's are two explicit settings, never `None` - and passing one in
            # here would be refused as an unknown option, correctly: a silently dropped
            # option is a request the caller believes it made. What is F2's to bound is how
            # long a batch may spend generating before the run says so, because an endpoint
            # that answers every call slowly never trips a per-request timeout and the step
            # hangs instead.
            raise refuse(
                "generation_timeout",
                f"Generating this batch has taken {elapsed:.1f}s, over the configured "
                f"{settings.generation_timeout_s:.1f}s, with {len(completions)} of {total} "
                f"prompts answered. The whole batch is refused: a partial batch is not fed "
                f"to a step.",
                elapsed_s=round(elapsed, 3),
                limit_s=settings.generation_timeout_s,
                completed=len(completions),
                total=total,
            )
        window = list(prompts[start : start + chunk])
        try:
            # One call per bounded window. The window IS the concurrency bound: an
            # implementation parallelises within a call, and handing it the whole prompt
            # list would make the bound a comment rather than a mechanism.
            produced = provider.generate(window, params)
        except Refusal:
            raise
        except Exception as exc:
            raise refuse(
                "generation_failed",
                f"The inference provider failed while generating candidates "
                f"{start}-{start + len(window) - 1}: {exc}. The whole batch is refused. No "
                f"partial batch reaches a step and no completion is substituted - a "
                f"provider outage is not a training signal.",
                index=start,
                error=str(exc),
            ) from exc
        if len(produced) != len(window):
            raise refuse(
                "generation_short_reply",
                f"The provider returned {len(produced)} completions for {len(window)} "
                f"prompts. Refusing rather than joining what arrived: callers join "
                f"completions to prompts positionally, so a gap misattributes every "
                f"candidate after it.",
                expected=len(window),
                received=len(produced),
            )
        completions.extend(produced)

    identity = _identity_of(completions)
    step = None
    if current_step is not None and identity.base_url is None:
        step = int(current_step())
    return tuple(completions), identity, resolved_model(identity, step=step)


def _identity_of(completions: Sequence[Completion]) -> ProviderIdentity:
    """The one identity that produced these candidates. **Refuses rather than guessing.**

    Two refusals, not one: an empty batch has no identity to record, and a batch answered
    by two different models is not one batch - the record has a single ``resolved_model``
    field and writing either of the two would be a claim about candidates the other
    produced.
    """
    if not completions:
        raise refuse(
            "generating_identity_unresolved",
            "No candidate was generated, so there is no model identity to record. A "
            "self-generation batch records the resolved model, and a guessed identity "
            "is worse than a refusal.",
        )
    identities = {completion.provider.record() for completion in completions}
    if len(identities) > 1:
        raise refuse(
            "generating_identity_ambiguous",
            f"These candidates were produced by {len(identities)} different models "
            f"({sorted(identities)}), and a batch record carries one resolved_model. "
            f"Refusing rather than recording one of them: candidates generated by two "
            f"different models are not interchangeable.",
            identities=sorted(identities),
        )
    return completions[0].provider
