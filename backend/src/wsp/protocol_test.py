"""The endpoint protocol test (feature 018; FR-018.8, F18-D7; FTDD §5.3; FTID §3.6).

A short ``inspect`` session on a small built-in bundle, through the NORMAL run path: the same
``wsp.runs.prepare_start`` and ``create_run`` as ``POST /wsp/runs``, the gateway and its metering,
one worker slot, and the same approval (none for a local endpoint, ``wsp_session_external`` for an
external one). It tests the endpoint's CURRENT ``action_protocol``; the run's list row then shows
``refused_turns`` (FR-018.11a). To compare the modes, the operator changes the protocol (the PATCH)
and runs it again. No contract changes.

**The provider is ``miwsp_engine``, always** (018-P2 deviation P2-D5). The action protocol and the
refused-turn count are the engine's: ``weightspace`` reads neither and writes no ``engine`` block,
so a protocol test on it would report nothing. Until ``WSP_PROVIDERS_AVAILABLE`` names the engine
the test is refused ``provider_unavailable``, by name.

**The built-in bundle** is generated by ``wsp.fixture_bundle.make_bundle`` (rule ``mean``,
``d_model`` 8, 24 rows, seed 0): the generator the tests use, so tests and production share one.
It holds no real activations, so its sensitivity is ``not_sensitive`` with basis source ``none``.
It passes the same checks as an import (``bundles._check_manifest``, ``bundles.check_files``: the
schema, the RFC 8785 digest, every tensor hash, the row-ids digest and parity) and is stored by
the same atomic rename, content-addressed under ``WSP_BUNDLE_ROOT/bundles/<sha>/``. Its row's
``owner`` is ``miforge`` (an import accepts ``miworkbench`` only, so no import can make such a
row), which is how the driver knows it need not ask miWorkbench for its sensitivity. It is created
on first use; later calls return the row.

**Thinking (2026-11-21).** The test runs with the endpoint's CURRENT ``thinking`` too (no
override), so the operator can verify a server honours it: the run's list row carries the
frozen ``thinking`` and ``reasoning_returned`` (whether any reply came back with reasoning).
With thinking on, the token budget grows by one reasoning allowance per step
(:func:`budgets_for`), so a test of a thinking endpoint is not stopped by its own reasoning.
"""

from __future__ import annotations

import datetime as dt
import os
import shutil
import tempfile
from pathlib import Path
from typing import Any

import sqlalchemy as sa
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from core.errors import refuse
from wsp import bundles, runs
from wsp.endpoints import DEFAULT_THINKING_TOKENS
from wsp.models import WspBundle, WspEndpoint
from wsp.providers import registry
from wsp.settings import WSPSettings, get_wsp_settings

#: The built-in bundle's row owner: never an import's (``bundles.parse_request`` admits only
#: ``miworkbench``), so a row with it was made here.
BUILTIN_OWNER = "miforge"
#: ``^wsb_[0-9a-z]{6,40}$`` (the bundle contract's pattern).
BUNDLE_ID = "wsb_miforgeprotocoltest1"
PROVIDER = "miwsp_engine"
TASK = "Read the weight tensor, call one observation tool, then submit a one-line description."
BUDGETS = {"max_steps": 6, "forward_passes": 1, "tokens": 20_000, "time_s": 300}
OBSERVATION_TOOLS = [{"name": "practice_metrics", "version": "2", "cost": 1}]
CALLER_REF_PREFIX = "protocol_test:"
MAX_CALLER_REF = 64


def is_builtin(bundle: WspBundle) -> bool:
    """The protocol test's own bundle: generated here, holding no real data."""
    return bundle.owner == BUILTIN_OWNER


def ensure_test_bundle(session: Session, settings: WSPSettings | None = None) -> WspBundle:
    """The built-in bundle's row, generating, checking and storing it on first use."""
    settings = settings or get_wsp_settings()
    row = _row(session)
    if row is not None and bundles.store_dir(settings, row.bundle_sha256).is_dir():
        return row
    manifest = _generate_and_store(settings, row)
    if row is not None:
        return row
    row = WspBundle(
        bundle_sha256=manifest["bundle_sha256"],
        owner=BUILTIN_OWNER,
        bundle_id=BUNDLE_ID,
        bundle_kind=manifest["bundle_kind"],
        artifact_kind=manifest["identity"]["artifact_kind"],
        artifact_id=manifest["identity"]["artifact_id"],
        detector_digest=None,
        model=manifest["identity"]["model"],
        layer=int(manifest["identity"]["layer"]),
        sensitivity_value=manifest["sensitivity"]["value"],
        manifest=manifest,
        bytes=sum(int(f["bytes"]) for f in manifest["files"]),
        import_status="imported",
        received_at=dt.datetime.now(dt.UTC),
        received_by=BUILTIN_OWNER,
        import_failure=None,
    )
    try:
        with session.begin_nested():
            session.add(row)
            session.flush()
    except IntegrityError:
        # Another protocol test stored it first: the content is the same, so its row is ours.
        found = _row(session)
        if found is None:  # pragma: no cover - the conflict was on another key
            raise
        return found
    return row


def _row(session: Session) -> WspBundle | None:
    return session.scalar(
        sa.select(WspBundle).where(
            WspBundle.owner == BUILTIN_OWNER, WspBundle.bundle_id == BUNDLE_ID
        )
    )


def _generate_and_store(settings: WSPSettings, row: WspBundle | None) -> dict[str, Any]:
    from core.atomic_dir import atomic_dir
    from wsp.fixture_bundle import make_bundle

    parent = Path(settings.wsp_bundle_root) / "bundles"
    parent.mkdir(parents=True, exist_ok=True)
    # Generated on the store's own filesystem, so the files move into place by rename.
    staging = Path(tempfile.mkdtemp(prefix=".protocol-test-", dir=parent))
    try:
        fx = make_bundle(
            staging,
            rule="mean",
            d_model=8,
            rows=24,
            seed=0,
            bundle_id=BUNDLE_ID,
            basis_source="none",
            description="miForge's built-in protocol-test probe (generated; no real data).",
        )
        manifest = fx.manifest
        if row is not None and row.bundle_sha256 != manifest["bundle_sha256"]:
            raise refuse(
                "wsp_bundle_hash_mismatch",
                "The built-in protocol-test bundle no longer generates the bytes its row records; "
                "its store directory is missing. Remove the row (owner miforge) and run the test "
                "again.",
            )
        request = bundles.ImportRequest(
            manifest["identity"]["owner"], BUNDLE_ID, manifest["bundle_sha256"]
        )
        bundles._check_manifest(manifest, request, settings)
        bundles.check_files(manifest, staging)
        dest = bundles.store_dir(settings, manifest["bundle_sha256"])
        if dest.is_dir():
            bundles.check_files(manifest, dest)
        else:
            with atomic_dir(dest, latest_link=False) as tmp:
                for entry in manifest["files"]:
                    os.replace(staging / entry["name"], tmp / entry["name"])
        return manifest
    finally:
        shutil.rmtree(staging, ignore_errors=True)


def budgets_for(endpoint: WspEndpoint | None) -> dict[str, int]:
    """:data:`BUDGETS`, plus one reasoning allowance per step when the endpoint thinks."""
    budgets = dict(BUDGETS)
    if endpoint is not None and endpoint.thinking == "on":
        allowance = endpoint.thinking_tokens or DEFAULT_THINKING_TOKENS
        budgets["tokens"] += budgets["max_steps"] * int(allowance)
    return budgets


def start_body(
    endpoint_id: str,
    bundle: WspBundle,
    caller_ref: str | None,
    budgets: dict[str, int] | None = None,
) -> dict[str, Any]:
    """The fixed start body (FTDD §5.3): a short inspect session with one observation tool."""
    ref = CALLER_REF_PREFIX + endpoint_id + ("" if caller_ref is None else f":{caller_ref}")
    return {
        "bundle": {
            "owner": bundle.owner,
            "bundle_id": bundle.bundle_id,
            "bundle_sha256": bundle.bundle_sha256,
        },
        "kind": "inspect",
        "mode": "session",
        "task": TASK,
        "endpoint_id": endpoint_id,
        "provider": {"id": PROVIDER},
        "sensitivity": bundle.sensitivity_value,
        "primary_sets": ["eval"],
        "budgets": dict(BUDGETS if budgets is None else budgets),
        "observation_tools": [dict(t) for t in OBSERVATION_TOOLS],
        "caller_ref": ref,
    }


def prepare(
    session: Session,
    endpoint_id: str,
    body: object,
    caller: str,
    settings: WSPSettings | None = None,
) -> runs.Prepared:
    """Validate the request, ensure the bundle, and freeze the run exactly as ``POST /wsp/runs``
    would (``runs.prepare_start``). Writes only the built-in bundle."""
    settings = settings or get_wsp_settings()
    if not isinstance(body, dict):
        raise refuse("validation_failed", "The body is a JSON object: {caller_ref?}.")
    other = sorted(str(k) for k in body if k != "caller_ref")
    if other:
        raise refuse(
            "validation_failed",
            f"The protocol test takes only caller_ref; refused: {', '.join(other)}.",
            fields=other,
        )
    caller_ref = body.get("caller_ref")
    if caller_ref is not None and (
        not isinstance(caller_ref, str) or not 0 < len(caller_ref) <= MAX_CALLER_REF
    ):
        raise refuse(
            "validation_failed", f"caller_ref is a string of 1 to {MAX_CALLER_REF} characters."
        )
    endpoint = runs.live_endpoint(session, endpoint_id)
    if endpoint is None:
        raise refuse("wsp_endpoint_unknown", "No such editor endpoint; register it first.")
    # Refuse an unavailable engine or an unconfigured WSP before generating anything.
    registry.get(PROVIDER, settings)
    runs.require_configured(settings)
    bundle = ensure_test_bundle(session, settings)
    return runs.prepare_start(
        session,
        start_body(endpoint_id, bundle, caller_ref, budgets_for(endpoint)),
        caller,
        settings,
    )
