"""Reader of ``docs/legacy-identifiers.md``, the census export (feature 015; FTID §3.7, CF-1).

The export is GENERATED by miSuite ``census.py --export miForge`` and never edited here. It is
the one source of every rule the frozen-identifier test, the brand guard and the origin-header
test apply: register entries (what must never be renamed), the env/host/repo rename tables and
the brand guard's phase rules. Nothing in the test tree keeps its own copy of those lists.

The private repository commits the full variant; the public mirror strips it and keeps
``legacy-identifiers.public.md``, which omits records the mirror may not carry and names them
in ``withheld`` (CF-2). :func:`load` reads the full file, else the public one, else fails.

The reader REFUSES anything outside the format, naming the offender, rather than guessing: an
unknown key, a regex flag in ``flags`` (CF-1: flags are inline in ``pattern``), a ``locations``
key, an inline modifier group in ``pattern_js`` (CF-16), ``\\A``/``\\Z``/``(?P``/``(?#`` (CF-25 m5),
a guard ``effect`` other than deny/allow, a header without ``closed`` (CF-21), a host record
without a boolean ``observed`` (CF-24), and a literal its own pattern does not match.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[3]
FULL = Path("docs/legacy-identifiers.md")
PUBLIC = Path("docs/legacy-identifiers.public.md")
#: An absolute path here replaces the committed export (scratch copies for controls and tests).
OVERRIDE_ENV = "LEGACY_IDENTIFIERS_EXPORT"

PHASES = ("P0", "P1", "P2", "P3", "P4", "P5", "P6", "P7", "P8")
HEADER_KEYS = ("format", "repo", "variant", "register_hash", "phase", "closed", "withheld")
#: Optional header keys and the only values each may take. ``forbidden_list: "unread"`` marks a
#: public variant written with ``census.py --public-unchecked`` before the suite has read
#: miForge's mirror forbidden-content list (S001 FTASKS 0.53); it goes away once ``--public``
#: can check it. Any other value, or the key on the full variant, is refused.
OPTIONAL_HEADER_KEYS: dict[str, frozenset[str]] = {"forbidden_list": frozenset({"unread"})}
SECTION_KEYS: dict[str, tuple[str, ...]] = {
    "entry": (
        "section",
        "id",
        "kind",
        "group",
        "status",
        "retire_phase",
        "pattern",
        "pattern_js",
        "js_flags",
        "literals",
        "exercise",
        "flags",
    ),
    "env": ("section", "old", "new", "status"),
    "host": ("section", "old", "new", "status", "observed"),
    "history_tool": ("section", "old", "new"),
    "repo": ("section", "old", "new", "status"),
    "guard": (
        "section",
        "id",
        "pattern",
        "pattern_js",
        "js_flags",
        "effect",
        "from_phase",
        "until_phase",
    ),
}
ENTRY_STATUS = frozenset({"frozen", "scheduled", "retired"})
RENAME_STATUS = frozenset({"transition", "retired"})
FLAGS = frozenset({"history_only", "text_only", "public_withheld", "pending"})
INLINE_FLAG = re.compile(r"\(\?[a-zA-Z]+[:)]")
FORBIDDEN_SYNTAX = ("\\A", "\\Z", "(?P", "(?#")
EXERCISE = re.compile(
    r"^(pytest:[^\s:]+\.py::\S.*|vitest:[^\s:]+\.(test|spec)\.(ts|tsx|js|jsx)::\S.*)$"
)


#: The private source organisation, built at runtime: the tests ship to the public mirror,
#: whose census export withholds the private repository names (census ``ef57482``), so the
#: file must not carry them in full either (015 review item 4).
PRIVATE = "Onegai" + "shimas"


class ExportError(ValueError):
    """The export is not in the format; the message names the offending record."""


@dataclass(frozen=True)
class Export:
    path: Path
    header: dict[str, Any]
    entries: list[dict[str, Any]] = field(default_factory=list)
    env: list[dict[str, Any]] = field(default_factory=list)
    host: list[dict[str, Any]] = field(default_factory=list)
    history_tools: list[dict[str, Any]] = field(default_factory=list)
    repo: list[dict[str, Any]] = field(default_factory=list)
    guards: list[dict[str, Any]] = field(default_factory=list)

    @property
    def variant(self) -> str:
        return str(self.header["variant"])

    @property
    def withheld(self) -> list[str]:
        return list(self.header["withheld"])

    @property
    def phase(self) -> str:
        return str(self.header["phase"])

    @property
    def closed(self) -> str | None:
        closed = self.header["closed"]
        return None if closed is None else str(closed)

    def entry(self, entry_id: str) -> dict[str, Any] | None:
        return next((e for e in self.entries if e["id"] == entry_id), None)

    def withholds(self, key: str) -> bool:
        """Whether the public variant left out the record with this :func:`record_key`."""
        return key in self.header["withheld"]


def withheld_key(section: str, old: str) -> str:
    """The id census writes in ``withheld`` for an env/host/history_tool/repo record: a stand-in,
    so the public file does not carry the very name it withholds (census ``ef57482``):
    ``<section>:sha256:`` + the first 16 hex of the SHA-256 of ``old``."""
    return f"{section}:sha256:{hashlib.sha256(old.encode()).hexdigest()[:16]}"


def record_key(record: dict[str, Any]) -> str:
    """How ``withheld`` names a record: an entry or guard by its id, the rest by stand-in."""
    if record.get("section") in ("entry", "guard"):
        return str(record["id"])
    return withheld_key(str(record["section"]), str(record["old"]))


def phase_index(phase: str | None) -> int:
    """``None`` (nothing closed yet) is -1; P0..P8 are 0..8."""
    if phase is None:
        return -1
    if phase not in PHASES:
        raise ExportError(f"unknown phase {phase!r}")
    return PHASES.index(phase)


def export_path(repo_root: Path = REPO_ROOT) -> Path:
    override = os.environ.get(OVERRIDE_ENV)
    if override:
        return Path(override)
    full = repo_root / FULL
    if full.is_file():
        return full
    public = repo_root / PUBLIC
    if public.is_file():
        # This repository's own tree reads the public variant ONLY as the mirror snapshot, so no
        # withheld-record skip (or `variant == "public"` branch) can fire on the private CI.
        from tests.support.mirror_snapshot import mirror_snapshot

        if repo_root.resolve() == REPO_ROOT.resolve() and not mirror_snapshot(repo_root):
            raise ExportError(
                f"{full} is missing and {repo_root} is not the mirror snapshot: only the mirror "
                f"may read {public} in its place (CF-2). Regenerate it with miSuite "
                f"`census.py --export miForge`."
            )
        return public
    raise ExportError(
        f"neither {full} nor {public} exists: generate them with miSuite "
        f"`census.py --export miForge` (and `--public`); they are never written by hand"
    )


def load(repo_root: Path = REPO_ROOT) -> Export:
    path = export_path(repo_root)
    return parse(path.read_text("utf-8"), path=path)


def _block(text: str) -> list[str]:
    blocks = re.findall(r"^```jsonl\n(.*?)^```\s*$", text, re.S | re.M)
    if len(blocks) != 1:
        raise ExportError(f"expected exactly one ```jsonl block, found {len(blocks)}")
    return [line for line in blocks[0].splitlines() if line.strip()]


def _check_pattern(where: str, record: dict[str, Any]) -> None:
    for key in ("pattern", "pattern_js"):
        value = record[key]
        if not isinstance(value, str) or not value:
            raise ExportError(f"{where}: {key} must be a non-empty string")
        for token in FORBIDDEN_SYNTAX:
            if token in value:
                raise ExportError(f"{where}: {key} uses {token}, which census rejects (CF-25 m5)")
    if INLINE_FLAG.search(record["pattern_js"]):
        raise ExportError(
            f"{where}: pattern_js carries an inline flag group; flags go in js_flags (CF-16)"
        )
    if record["js_flags"] not in ("", "i"):
        raise ExportError(f"{where}: js_flags {record['js_flags']!r} is not '' or 'i'")
    try:
        re.compile(record["pattern"])
    except re.error as exc:
        raise ExportError(f"{where}: pattern does not compile: {exc}") from exc


def _phase_or_null(where: str, value: Any) -> None:
    if value is not None and value not in PHASES:
        raise ExportError(f"{where}: phase {value!r} is not P0..P8 or null")


def parse(text: str, *, path: Path = Path("<text>")) -> Export:
    lines = _block(text)
    if not lines:
        raise ExportError("the jsonl block is empty")
    header = json.loads(lines[0])
    if header.get("format") != 1:
        raise ExportError(f"header format {header.get('format')!r} is not 1")
    missing = [k for k in HEADER_KEYS if k not in header]
    if missing:
        raise ExportError(f"header lacks {missing} (CF-21 requires 'closed')")
    unknown = set(header) - set(HEADER_KEYS) - set(OPTIONAL_HEADER_KEYS)
    if unknown:
        raise ExportError(f"header carries unknown keys {sorted(unknown)}")
    for key, allowed in OPTIONAL_HEADER_KEYS.items():
        if key in header and header[key] not in allowed:
            raise ExportError(f"header {key}={header[key]!r} is not one of {sorted(allowed)}")
        if key in header and header.get("variant") != "public":
            raise ExportError(f"header {key} belongs only to the public variant")
    if header["variant"] not in ("full", "public"):
        raise ExportError(f"header variant {header['variant']!r}")
    if header["phase"] not in PHASES:
        raise ExportError(f"header phase {header['phase']!r}")
    _phase_or_null("header closed", header["closed"])

    sections: dict[str, list[dict[str, Any]]] = {name: [] for name in SECTION_KEYS}
    for number, line in enumerate(lines[1:], start=2):
        record = json.loads(line)
        section = record.get("section")
        if section not in SECTION_KEYS:
            raise ExportError(f"line {number}: unknown section {section!r}")
        where = f"line {number} ({section} {record.get('id') or record.get('old')})"
        if "locations" in record:
            raise ExportError(f"{where}: carries 'locations', which never enter the export (CF-1)")
        keys = SECTION_KEYS[section]
        absent = [k for k in keys if k not in record]
        extra = [k for k in record if k not in keys]
        if absent or extra:
            raise ExportError(f"{where}: missing keys {absent}, unknown keys {extra}")
        if section == "entry":
            if record["status"] not in ENTRY_STATUS:
                raise ExportError(f"{where}: status {record['status']!r}")
            bad = [f for f in record["flags"] if f not in FLAGS]
            if bad:
                raise ExportError(f"{where}: flags {bad} are outside {sorted(FLAGS)} (CF-1)")
            _check_pattern(where, record)
            exercise = record["exercise"]
            if exercise is not None and not EXERCISE.match(exercise):
                raise ExportError(f"{where}: exercise {exercise!r} is not a test id")
            for literal in record["literals"]:
                if not re.search(record["pattern"], literal):
                    raise ExportError(
                        f"{where}: literal {literal!r} does not match its own pattern (CF-25 m5)"
                    )
        elif section == "guard":
            if record["effect"] not in ("deny", "allow"):
                raise ExportError(f"{where}: guard effect {record['effect']!r} (deny|allow)")
            _phase_or_null(where, record["from_phase"])
            _phase_or_null(where, record["until_phase"])
            _check_pattern(where, record)
        elif section in ("env", "host", "repo"):
            if record["status"] not in RENAME_STATUS:
                raise ExportError(f"{where}: status {record['status']!r}")
            if section == "host" and not isinstance(record["observed"], bool):
                raise ExportError(f"{where}: host record needs a boolean 'observed' (CF-24)")
        sections[section].append(record)
    return Export(
        path=path,
        header=header,
        entries=sections["entry"],
        env=sections["env"],
        host=sections["host"],
        history_tools=sections["history_tool"],
        repo=sections["repo"],
        guards=sections["guard"],
    )


def active_guards(export: Export, phase: str | None = None) -> list[dict[str, Any]]:
    """Guard rows in force at ``phase`` (default: the header's): from ``from_phase`` (null = P0)
    up to, not including, ``until_phase`` (null = forever)."""
    now = phase_index(phase or export.phase)
    return [
        g
        for g in export.guards
        if now >= phase_index(g["from_phase"] or "P0")
        and (g["until_phase"] is None or now < phase_index(g["until_phase"]))
    ]


def with_header(text: str, **changes: Any) -> str:
    """The same export text with header fields replaced (for phase/closed rewrite cases)."""
    lines = text.split("\n")
    for index, line in enumerate(lines):
        if line.startswith('{"format"'):
            header = json.loads(line)
            header.update(changes)
            lines[index] = json.dumps(header, ensure_ascii=False, separators=(",", ":"))
            return "\n".join(lines)
    raise ExportError("no header line")
