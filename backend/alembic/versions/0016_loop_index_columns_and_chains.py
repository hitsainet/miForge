"""F6's index columns on ``mf_runs``, the two chain tables, and ``merge`` finally dropped.

Revision ID: 0016_f6_loop
Revises: 0015_pack_cols
Create Date: 2026-10-14

F6's owed DDL, handed over in its report because the Alembic graph is serialised through one
owner: two revisions off the same parent make ``alembic upgrade head`` fail for everyone on a
clean clone.

**Nothing here is on F6's critical path.** Every value is already durable in the run log,
which ADR-004 makes authoritative, and F6 reads it from there. These columns make the run
list and the run screen a query instead of a file scan per run.

## Three parts of the handed-over SQL could not be used as written, and the reason matters

F6's DDL was PostgreSQL-flavoured. The suite's default engine is **SQLite**
(``tests/support/db.py``), so each of these would have passed review and failed on the
engine every developer runs:

* ``TIMESTAMPTZ`` and ``GENERATED BY DEFAULT AS IDENTITY`` → ``sa.DateTime(timezone=True)``
  and ``autoincrement=True``.
* ``ALTER TABLE mf_runs ADD CONSTRAINT …`` → **SQLite cannot add a constraint to an existing
  table at all.** Four new CHECK constraints and the ``run_type`` narrowing therefore need
  one table rebuild, which is the expensive part of this revision and is done once.
* ``advance_on @> '["retention_floor"]'::jsonb`` → **dropped, not translated.** It is a JSONB
  containment operator SQLite cannot evaluate, and a constraint present on one engine and
  absent on the other is exactly the divergence ``tests/support/db.py`` names as its blind
  spot. F6 enforces that rule in **three** layers of Python, each with a red mutation control
  (M-8, M-8b, M-8c). Three tested layers on both engines beat a fourth on one; the reasoning
  is recorded in ``services/chains/tables.py`` rather than lost.

## The ``mf_runs`` rebuild, and what ``0014`` taught about it

SQLAlchemy does not reflect SQLite CHECK constraints, so a ``batch_alter_table`` left to
reflect rebuilds the table **without** them — silently, while reporting success. ``0014``
also lost the table's one index that way, because its ``copy_from`` omitted it and the hand
verification printed ``indexes kept: []`` and was read past. So the table is declared here in
full: **every column through revision ``0015``, all three existing CHECK constraints, the
pack foreign key, the primary key, and the index.**

## ``merge`` is dropped from ``run_type``, and it is now PROVED rather than assumed

``0014`` left it permitted *"rather than removed because F6 is not built, so nothing has yet
proved no submit path produces one."* F6 is built, and the proof is three-part:
``services/run_launch.launch`` is the only path that creates an ``mf_runs`` row,
``RunDefinition.run_type`` is validated through F8's registry (``change|create|adapter``), and
``workers/merge_tasks`` writes ``mf_merges`` and never a run row. A merge is an **operation**,
not a run — F6's FR-006.55 gives the mechanical reason: a stepless run row would be refused
at submit for having no stop condition, never heartbeat, and be reaped by the janitor.

## ``completed_names_its_reason`` was asked for, built, and then DROPPED — it cannot survive

F6's DDL asked for ``CHECK (status <> 'completed' OR stop_reason IS NOT NULL)``, on the sound
argument that *"a completed row that cannot say why it stopped is a record an operator cannot
act on."* It was built, and the round-trip verification found it **makes this revision
non-reversible on any real installation**:

the downgrade drops ``stop_reason``, so every completed run comes back with ``NULL`` there,
and the next upgrade's rebuild then **refuses its own existing rows**. Not a test artifact — a
property of the pair. Three ways out were considered and two are worse:

* **Backfill a reason on upgrade.** There is no honest value. ``step_count`` would claim a run
  reached a step budget it may never have had, in the table an operator reads to find out what
  happened — the fabricated value ADR-018 forbids, and the same argument that makes a ``merge``
  row a refusal rather than a rewrite.
* **Refuse the upgrade** when a completed run lacks a reason. Correct but hostile: it makes
  downgrade-then-upgrade impossible for anyone with a finished run, which is every real
  installation after a week.
* **Drop the constraint** and keep the column. Taken.

The property is not lost, it moves: F6 derives the reason by **precedence** at the boundary
and mutation **M-19** (``stop_reason`` permanently null) is **red**. So it is enforced where
the value is written, on both engines, by a control that has been seen to fail — which is
strictly better evidence than a constraint that cannot round-trip. The other three new CHECKs
survive a cycle untouched, because ``NULL`` satisfies all three.

**The general shape, since this is the second instance in one revision:** a constraint that
creates a worse problem than it solves does not belong in the schema. The first was the JSONB
containment check, dropped for portability; this one is dropped for reversibility. Both are
enforced in tested code instead, and both reasons are written down rather than left for
someone to rediscover by hitting them.

**An existing ``merge`` row makes this migration REFUSE rather than rewrite.** F6 asked for
that explicitly and it is right: there is no correct value to rewrite such a row to. ``create``
would claim weights were made from nothing, ``change`` that a model was trained. Either is a
fabricated history in a table an operator reads to find out what happened, and ADR-018 forbids
a guessed value precisely because it is silent. A refusal naming the rows is recoverable.
"""

